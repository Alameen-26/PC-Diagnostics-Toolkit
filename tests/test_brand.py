# tests/test_brand.py
# Added in v0.2.0: tests for the "Made by NiyiSoft" maker's mark.
"""The NiyiSoft mark appears in every report, stays self-contained and small,
has alt text, and degrades to plain text if the image files are missing."""
from __future__ import annotations

import re

from pcdiag.analysis import analyze, recommend_upgrades
from pcdiag.fixtures import ALL_FIXTURES
from pcdiag.report import brand, render_html, render_markdown
from pcdiag.terminal import summary_lines


def _render(name: str = "slow_old_laptop"):
    snap = ALL_FIXTURES[name]() if callable(ALL_FIXTURES[name]) else ALL_FIXTURES[name]
    findings = analyze(snap)
    recs = recommend_upgrades(snap, findings)
    return snap, findings, recs


def test_html_report_has_badge_with_alt_text_at_the_end():
    html = render_html(*_render())
    assert 'data-brand="niyisoft"' in html
    assert 'alt="Made by NiyiSoft"' in html
    # The mark comes after all report content, just before </main>.
    assert html.index('data-brand="niyisoft"') > html.index("Generated by pcdiag")
    assert html.rstrip().endswith("</main></body></html>")


def test_badge_is_embedded_not_linked_and_small():
    html = render_html(*_render())
    uris = re.findall(r'src="(data:image/png;base64,[A-Za-z0-9+/=]+)"', html)
    assert len(uris) == 2  # light-mode and dark-mode variants
    for uri in uris:
        assert len(uri) < 12_000  # each PNG is ~6 KB, so the report stays light
    assert 'src="http' not in html  # still no external assets


def test_dark_mode_variant_is_hidden_from_screen_readers():
    html = render_html(*_render())
    assert 'class="on-dark"' in html and 'aria-hidden="true" width="140"' in html
    assert "prefers-color-scheme: dark){.brand .on-light{display:none}" in html


def test_fallback_to_text_when_assets_missing(monkeypatch):
    # Changed in v0.2.0: the badge is base64 text in a module, so "missing" means no data module.
    brand._data_uri.cache_clear()
    monkeypatch.setattr(brand, "_badge_data", None)
    try:
        out = brand.brand_html()
        assert 'data-brand="text"' in out and "Made by NiyiSoft" in out and "<img" not in out
    finally:
        brand._data_uri.cache_clear()


def test_markdown_and_terminal_carry_the_mark():
    snap, findings, recs = _render()
    assert "Made by NiyiSoft" in render_markdown(snap, findings, recs)
    first = summary_lines(snap)[0]
    assert first.endswith("Made by NiyiSoft") and first.isascii()
